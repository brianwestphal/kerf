import { existsSync } from 'node:fs';

// Generated Kerf UI view modules (docs/26-ui-editor.md §5.2) are read-only:
// application code integrates through their exports and never edits them.
// The generator records a digest of the module body in its header; this rule
// recomputes it, so a hand edit (or a half-applied regeneration) is reported
// without access to the source document.

const STAMP =
  /^\/\/ kui-view: \d+ contract (kui1:[0-9a-f]{16}) source kui1:[0-9a-f]{16} body (kui1:[0-9a-f]{16})$/;
const GENERATED = '// GENERATED by kerf-ui-view';
const HEADER_LINES = 3;
const VIEW_FILE = /\.view\.(?:d\.ts|ts|js)$/;
const MASK = 0xffffffffffffffffn;

/**
 * `kui1:` + 16 hex digits of the 64-bit FNV-1a hash of `text`'s UTF-8 bytes —
 * the same digest `@kerfjs/ui/view`'s `viewDigest` computes (pinned by a
 * parity test), duplicated so the plugin needs no runtime dependency on it.
 */
export function viewDigest(text) {
  let hash = 0xcbf29ce484222325n;
  for (const byte of new TextEncoder().encode(text)) {
    hash ^= BigInt(byte);
    hash = (hash * 0x100000001b3n) & MASK;
  }
  return `kui1:${hash.toString(16).padStart(16, '0')}`;
}

/** The `.kui.json` document a generated module's path would come from. */
const documentFor = (filename) => filename.replace(VIEW_FILE, '.kui.json');

export default {
  meta: {
    type: 'problem',
    docs: {
      description:
        'Disallow hand edits to generated Kerf UI view modules (*.view.ts).',
      url: 'https://github.com/brianwestphal/kerf/blob/main/eslint-plugin/docs/rules/no-generated-view-edits.md',
    },
    schema: [],
    messages: {
      edited:
        'This generated view module was edited by hand (its body no longer matches its kerf-ui-view header). Regenerate it with `kerf-ui-view generate`; put behavior, overrides, and wiring in your own files that import it.',
      header:
        'This generated view module has a damaged kerf-ui-view header. Regenerate it with `kerf-ui-view generate` instead of editing it.',
      missing:
        'A module beside a `.kui.json` view document must be the generated one. Run `kerf-ui-view generate` rather than writing it by hand.',
    },
  },
  create(context) {
    const filename = context.filename ?? context.getFilename();
    const sourceCode = context.sourceCode ?? context.getSourceCode();
    return {
      Program(node) {
        // Git checkouts may convert line endings; the digest covers LF text.
        const lines = sourceCode.text.replace(/\r\n/g, '\n').split('\n');
        if (!lines[0]?.startsWith(GENERATED)) {
          if (VIEW_FILE.test(filename) && existsSync(documentFor(filename))) {
            context.report({ node, messageId: 'missing' });
          }
          return;
        }
        const stamp = STAMP.exec(lines[1] ?? '');
        const contract = /^\/\/ kui-contract: (.*)$/.exec(lines[2] ?? '');
        if (!stamp || !contract) {
          context.report({ node, messageId: 'header' });
          return;
        }
        // The body digest covers the code; the contract digest covers the
        // recorded contract line (its canonical JSON).
        if (
          viewDigest(lines.slice(HEADER_LINES).join('\n')) !== stamp[2] ||
          viewDigest(contract[1]) !== stamp[1]
        ) {
          context.report({ node, messageId: 'edited' });
        }
      },
    };
  },
};
