// generateView: turns a valid view document into its read-only view module
// (docs/26-ui-editor.md §4). Output is plain TypeScript (or JavaScript plus a
// .d.ts) that calls component functions directly — no JSX, no compiler in the
// consumer's build. Same document and catalogs in, byte-identical code out.
import {
  canonicalJson,
  contractDigest,
  contractOf,
  propertyName,
  serializeContract,
  typeText,
  viewDigest,
} from './contract.mjs';
import { channelOf, parseCssCall, zonePropOf } from './validate.mjs';

export const GENERATOR_VERSION = 1;
const HEADER_LINES = 3;

const isObject = (value) =>
  value !== null && typeof value === 'object' && !Array.isArray(value);
const lowerFirst = (name) => name[0].toLowerCase() + name.slice(1);
const literal = (value) => JSON.stringify(value);

// A tiny layout printer: expressions are built as docs and printed flat when
// they fit the line, otherwise broken one entry per line. Deterministic, so
// output never depends on the consumer's formatter.
const WIDTH = 100;
const raw = (text) => ({ raw: text });
const call = (prefix, arg, suffix = ')') => ({ call: prefix, arg, suffix });
const obj = (entries) => ({ obj: entries });
const arr = (items) => ({ arr: items });
const cond = (test, then, otherwise) => ({ cond: test, then, otherwise });
// An object entry is `[key, doc]`, or `[spread]` for `...expression`.
const entry = ([key, value]) =>
  value === undefined ? key : `${key}: ${flat(value)}`;

function flat(doc) {
  if (doc.raw !== undefined) return doc.raw;
  if (doc.call !== undefined) return `${doc.call}${flat(doc.arg)}${doc.suffix}`;
  if (doc.obj)
    return doc.obj.length ? `{ ${doc.obj.map(entry).join(', ')} }` : '{}';
  if (doc.cond !== undefined) {
    return `(${doc.cond} ? ${flat(doc.then)} : ${flat(doc.otherwise)})`;
  }
  return `[${doc.arr.map(flat).join(', ')}]`;
}

/** Prints a doc starting at column `indent`. */
export function printDoc(doc, indent = 0) {
  const single = flat(doc);
  if (indent + single.length <= WIDTH || doc.raw !== undefined) return single;
  const pad = ' '.repeat(indent + 2);
  const end = ' '.repeat(indent);
  if (doc.call !== undefined) {
    return `${doc.call}${printDoc(doc.arg, indent)}${doc.suffix}`;
  }
  if (doc.obj) {
    return `{
${doc.obj
  .map(([key, value]) =>
    value === undefined
      ? `${pad}${key},`
      : `${pad}${key}: ${printDoc(value, indent + 2)},`,
  )
  .join('\n')}\n${end}}`;
  }
  if (doc.cond !== undefined) {
    return `(${doc.cond}\n${pad}? ${printDoc(doc.then, indent + 4)}\n${pad}: ${printDoc(doc.otherwise, indent + 4)})`;
  }
  return `[\n${doc.arr.map((item) => `${pad}${printDoc(item, indent + 2)},`).join('\n')}\n${end}]`;
}

/** Lucide's export name for a kebab-case icon name (`a-arrow-down` → `AArrowDown`). */
export function lucideExportName(name) {
  return name
    .split('-')
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join('');
}

/**
 * The import specifier for a component module. A package specifier is used
 * as is. An absolute path (an app-source component whose catalog the caller
 * resolved) becomes relative to `importFrom`, the generated module's folder.
 * Pure string work, so it also runs in the browser.
 */
export function moduleSpecifier(specifier, importFrom) {
  if (!specifier.startsWith('/') || !importFrom) return specifier;
  const from = importFrom.split('/').filter(Boolean);
  const to = specifier.split('/').filter(Boolean);
  let shared = 0;
  while (
    shared < from.length &&
    shared < to.length - 1 &&
    from[shared] === to[shared]
  )
    shared += 1;
  const up = from.length - shared;
  const rest = to.slice(shared).join('/');
  return up === 0 ? `./${rest}` : `${'../'.repeat(up)}${rest}`;
}

/** The module path generated for a document path (`x.kui.json` → `x.view.ts`). */
export function viewModulePath(documentPath, target = 'ts') {
  const base = documentPath.replace(/\.kui\.json$/, '');
  return `${base}.view.${target === 'js' ? 'js' : 'ts'}`;
}

/** The import specifier of a composed document's generated module. */
function viewImport(src) {
  return `${src.replace(/\.kui\.json$/, '')}.view.js`;
}

/** The composed document's exported names, from its `name`. */
const namesOf = (name) => ({
  render: `render${name}`,
  inputs: `${name}Inputs`,
});

/**
 * Splits generated source into its header and body, and checks the body
 * against the header's recorded digest. Used by `kerf-ui-view check` and the
 * `kerfjs/no-generated-view-edits` lint rule.
 */
export function readViewHeader(code) {
  // A checkout may convert line endings; the digest covers LF text.
  const lines = code.replace(/\r\n/g, '\n').split('\n');
  const stamp =
    /^\/\/ kui-view: (\d+) contract (kui1:[0-9a-f]{16}) source (kui1:[0-9a-f]{16}) body (kui1:[0-9a-f]{16})$/.exec(
      lines[1] ?? '',
    );
  const recorded = /^\/\/ kui-contract: (.*)$/.exec(lines[2] ?? '');
  if (
    !lines[0]?.startsWith('// GENERATED by kerf-ui-view') ||
    !stamp ||
    !recorded
  ) {
    return undefined;
  }
  const body = lines.slice(HEADER_LINES).join('\n');
  let contract;
  try {
    contract = JSON.parse(recorded[1]);
  } catch {
    return undefined;
  }
  return {
    version: Number(stamp[1]),
    contractDigest: stamp[2],
    sourceDigest: stamp[3],
    bodyDigest: stamp[4],
    contract,
    // The contract line is the canonical JSON the contract digest hashes, so
    // an edited contract line is caught just like an edited body.
    intact:
      viewDigest(body) === stamp[4] && viewDigest(recorded[1]) === stamp[2],
  };
}

function header(sourceName, contract, sourceDigest, body) {
  return [
    `// GENERATED by kerf-ui-view from ${sourceName} — do not edit.`,
    `// kui-view: ${GENERATOR_VERSION} contract ${contractDigest(contract)} source ${sourceDigest} body ${viewDigest(body)}`,
    `// kui-contract: ${serializeContract(contract)}`,
  ].join('\n');
}

/** Collects imports as specifier → names, rendered sorted for determinism. */
function createImports() {
  const values = new Map();
  const types = new Map();
  const add = (map, specifier, name) => {
    if (!map.has(specifier)) map.set(specifier, new Set());
    map.get(specifier).add(name);
  };
  return {
    value: (specifier, name) => add(values, specifier, name),
    type: (specifier, name) => add(types, specifier, name),
    render(ts) {
      const specifiers = [
        ...new Set([...values.keys(), ...(ts ? types.keys() : [])]),
      ].sort();
      return specifiers
        .map((specifier) => {
          const names = [
            ...[...(values.get(specifier) ?? [])].sort(),
            ...(ts
              ? [...(types.get(specifier) ?? [])]
                  .sort()
                  .map((name) => `type ${name}`)
              : []),
          ];
          return `import { ${names.join(', ')} } from '${specifier}';`;
        })
        .join('\n');
    },
  };
}

function createEmitter(document, catalog, imports, importFrom) {
  const component = (type) => catalog.components.get(type)?.component;

  const value = (input, scope) => {
    if (isObject(input) && '$param' in input) {
      const param = document.params[input.$param];
      const read = `inputs.${input.$param}`;
      return raw(
        'default' in param ? `(${read} ?? ${literal(param.default)})` : read,
      );
    }
    if (isObject(input) && '$bind' in input) {
      const [head, ...rest] = input.$bind.split('.');
      return raw(
        [scope.has(head) ? head : `inputs.${head}`, ...rest].join('.'),
      );
    }
    if (isObject(input) && '$action' in input)
      return raw(literal(input.$action));
    if (isObject(input) && '$icon' in input) {
      const exported = lucideExportName(input.$icon);
      // Aliased so a Lucide name never collides with a component (List, Text).
      imports.value('lucide', `${exported} as lucide${exported}`);
      return raw(`lucide${exported}`);
    }
    if (isObject(input) && '$css' in input) {
      for (const helper of parseCssCall(input.$css)) {
        imports.value('@kerfjs/ui/css-values', helper);
      }
      return raw(input.$css.trim());
    }
    // An item slot (KF-SXDM56): content the application fills, as a zone's.
    if (isObject(input) && '$slot' in input)
      return raw(`slots.${input.$slot}()`);
    if (isObject(input)) {
      return obj(
        Object.keys(input)
          .sort()
          .map((key) => [propertyName(key), value(input[key], scope)]),
      );
    }
    if (Array.isArray(input))
      return arr(input.map((item) => value(item, scope)));
    return raw(literal(input));
  };

  /** Marker (and row key) attributes merged into a node's data-* channel. */
  const markers = (node, rowKey, base, scope) => {
    const entries = [];
    if (isObject(base) && !('$param' in base) && !('$bind' in base)) {
      for (const key of Object.keys(base).sort())
        entries.push([literal(key), value(base[key], scope)]);
    } else if (base !== undefined) {
      entries.push([`...${flat(value(base, scope))}`]);
    }
    entries.push(["'data-kerf-node'", raw(literal(node.id))]);
    if (rowKey) entries.push(["'data-key'", raw(`String(${rowKey})`)]);
    return obj(entries);
  };

  const children = (list, scope, slot) => {
    const items = list.map((child) => childExpr(child, scope, slot));
    return items.length === 1 ? items[0] : arr(items);
  };

  const childExpr = (child, scope, slot) => {
    if ('$each' in child) {
      const inner = new Map(scope).set(child.as, true);
      const template = nodeExpr(child.template, inner, child.key, slot);
      imports.value('kerfjs', 'each');
      return call(
        `each(${flat(value(child.$each, scope))}, (${child.as}) => `,
        template,
        `, { key: ${literal(child.template.id)} })`,
      );
    }
    if ('$if' in child) {
      const otherwise =
        'else' in child ? childExpr(child.else, scope, slot) : raw('null');
      return cond(
        flat(value(child.$if, scope)),
        childExpr(child.then, scope, slot),
        otherwise,
      );
    }
    if ('$slot' in child) {
      return isObject(child.input)
        ? call(`slots.${child.$slot}(`, value(child.input, scope))
        : raw(`slots.${child.$slot}()`);
    }
    return nodeExpr(child, scope, undefined, slot);
  };

  const nodeExpr = (node, scope, rowKey, slot) => {
    if (node.type === '#text') {
      const text = value(node.value, scope);
      if (!slot) return text;
      imports.value('kerfjs/jsx-runtime', 'jsx');
      return call(
        "jsx('span', ",
        obj([
          ['slot', raw(literal(slot))],
          ['children', text],
        ]),
      );
    }
    if (node.type === '#view') {
      const child = document.views[node.src];
      const names = namesOf(child.name);
      imports.value(viewImport(node.src), names.render);
      return call(`${names.render}(`, value(node.props ?? {}, scope));
    }
    const definition = component(node.type);
    const props = isObject(node.props) ? node.props : {};
    const entries = [];
    for (const name of Object.keys(props).sort()) {
      if (name === 'rootAttributes') continue;
      entries.push([propertyName(name), value(props[name], scope)]);
    }
    const zones = isObject(node.zones) ? node.zones : {};
    if (definition.source === 'webawesome') {
      entries.push(["'data-kerf-node'", raw(literal(node.id))]);
      if (rowKey) entries.push(["'data-key'", raw(`String(${rowKey})`)]);
      if (slot) entries.push(['slot', raw(literal(slot))]);
      const parts = Object.keys(zones)
        .sort()
        .flatMap((key) =>
          zones[key].map((child) =>
            childExpr(child, scope, key === 'default' ? undefined : key),
          ),
        );
      if (parts.length)
        entries.push(['children', parts.length === 1 ? parts[0] : arr(parts)]);
      imports.value('kerfjs/jsx-runtime', 'jsx');
      return call(`jsx(${literal(definition.tagName)}, `, obj(entries));
    }
    for (const key of Object.keys(zones).sort()) {
      entries.push([
        propertyName(zonePropOf(catalog, definition, key)),
        children(zones[key], scope),
      ]);
    }
    if (slot && definition.props.some((prop) => prop.name === 'slot')) {
      entries.push(['slot', raw(literal(slot))]);
    }
    // A component without the channel has no rootAttributes prop at all, so
    // validation already rejected one in its props.
    const channel = channelOf(definition);
    if (channel === 'rootAttributes') {
      entries.push([
        'rootAttributes',
        markers(node, rowKey, props.rootAttributes, scope),
      ]);
    } else if (channel === 'native') {
      // The component passes data-* props straight through to its root.
      entries.push(["'data-kerf-node'", raw(literal(node.id))]);
      if (rowKey) entries.push(["'data-key'", raw(`String(${rowKey})`)]);
    }
    imports.value(
      moduleSpecifier(definition.import, importFrom),
      definition.export,
    );
    return call(`${definition.export}(`, obj(entries));
  };

  return { root: (node) => nodeExpr(node, new Map(), undefined, undefined) };
}

function typesBlock(name, contract) {
  const inputs = Object.entries(contract.inputs);
  const actions = Object.entries(contract.actions);
  const slots = Object.entries(contract.slots);
  const refs = Object.entries(contract.refs);
  const lines = [];
  lines.push(
    inputs.length
      ? `export interface ${name}Inputs {\n${inputs
          .map(
            ([key, input]) =>
              `  readonly ${key}${input.optional ? '?' : ''}: ${input.type};`,
          )
          .join('\n')}\n}`
      : `export type ${name}Inputs = Readonly<Record<string, never>>;`,
  );
  lines.push(
    `export type ${name}Action = ${actions.length ? actions.map(([key]) => literal(key)).join(' | ') : 'never'};`,
  );
  lines.push(
    `export interface ${name}ActionContext {\n  readonly event: Event;\n  readonly target: HTMLElement;\n}`,
  );
  if (actions.some(([, scope]) => scope === 'row')) {
    lines.push(
      `export interface ${name}RowActionContext extends ${name}ActionContext {\n  /** The \`data-key\` of the row the action came from. */\n  readonly key: string;\n}`,
    );
  }
  lines.push(
    actions.length
      ? `export interface ${name}Handlers {\n${actions
          .map(
            ([key, scope]) =>
              `  ${propertyName(key)}(context: ${name}${scope === 'row' ? 'Row' : ''}ActionContext): void;`,
          )
          .join('\n')}\n}`
      : `export type ${name}Handlers = Readonly<Record<string, never>>;`,
  );
  lines.push(
    slots.length
      ? `export interface ${name}Slots {\n${slots
          .map(
            ([key, input]) =>
              `  ${key}(${input ? `input: ${input}` : ''}): SafeHtml;`,
          )
          .join('\n')}\n}`
      : `export type ${name}Slots = Readonly<Record<string, never>>;`,
  );
  lines.push(
    refs.length
      ? `export interface ${name}Refs {\n${refs
          .map(([key, ref]) =>
            ref.keyed
              ? `  readonly ${key}: (key: string) => ${ref.element} | null;`
              : `  readonly ${key}: ${ref.element};`,
          )
          .join('\n')}\n}`
      : `export type ${name}Refs = Readonly<Record<string, never>>;`,
  );
  return lines.join('\n\n');
}

// A parameter the body never reads is marked used, so the module compiles
// under a consumer's noUnusedParameters.
const unused = (body, ...names) =>
  names
    .filter((name) => !new RegExp(`\\b${name}\\b`).test(body))
    .map((name) => `  void ${name};\n`)
    .join('');

function functionsBlock(name, contract, rootExpr, ts) {
  const camel = lowerFirst(name);
  const t = (annotation) => (ts ? annotation : '');
  const actions = Object.entries(contract.actions);
  const refs = Object.entries(contract.refs);
  const optional = (entries) =>
    Object.values(entries).every((entry) => entry?.optional !== false);
  const blocks = [];
  if (rootExpr !== undefined) {
    const inputsDefault = optional(contract.inputs) ? ' = {}' : '';
    const slotsDefault =
      Object.keys(contract.slots).length === 0 ? ' = {}' : '';
    blocks.push(
      `export function render${name}(inputs${t(`: ${name}Inputs`)}${inputsDefault}, slots${t(`: ${name}Slots`)}${slotsDefault})${t(': SafeHtml')} {\n${unused(rootExpr, 'inputs', 'slots')}  return ${rootExpr};\n}`,
    );
  }
  const handlerLines = actions.map(([key, scope]) => {
    const context =
      scope === 'row'
        ? '{ event, target, key: rowKey(target) }'
        : '{ event, target }';
    return `    ${literal(key)}: (event, target) => handlers[${literal(key)}](${context}),`;
  });
  blocks.push(
    `export function wire${name}(root${t(': HTMLElement')}, handlers${t(`: ${name}Handlers`)})${t(': () => void')} {\n${unused(handlerLines.join(''), 'handlers')}  return delegateActions${t('<HTMLElement>')}(root, 'click', {\n${handlerLines.join('\n')}${handlerLines.length ? '\n' : ''}  });\n}`,
  );
  const refLines = refs.map(([key, ref]) =>
    ref.keyed
      ? `    ${key}: (key${t(': string')}) => rowRef(root, ${literal(ref.id)}, key)${t(` as ${ref.element} | null`)},`
      : `    ${key}: nodeRef(root, ${literal(ref.id)}, ${literal(key)})${t(` as ${ref.element}`)},`,
  );
  blocks.push(
    `export function ${camel}Refs(root${t(': ParentNode')})${t(`: ${name}Refs`)} {\n${unused(refLines.join(''), 'root')}  return {\n${refLines.join('\n')}${refLines.length ? '\n' : ''}  };\n}`,
  );
  if (actions.some(([, scope]) => scope === 'row')) {
    blocks.push(
      `function rowKey(target${t(': Element')})${t(': string')} {\n  return target.closest('[data-key]')?.getAttribute('data-key') ?? '';\n}`,
    );
  }
  if (refs.some(([, ref]) => !ref.keyed)) {
    blocks.push(
      `function nodeRef(root${t(': ParentNode')}, id${t(': string')}, name${t(': string')})${t(': Element')} {\n  const found = root.querySelector(\`[data-kerf-node="\${id}"]\`);\n  if (!found) throw new Error(\`${name} ref "\${name}" (\${id}) is not rendered\`);\n  return found;\n}`,
    );
  }
  if (refs.some(([, ref]) => ref.keyed)) {
    blocks.push(
      `function rowRef(root${t(': ParentNode')}, id${t(': string')}, key${t(': string')})${t(': Element | null')} {\n  for (const found of root.querySelectorAll(\`[data-kerf-node="\${id}"]\`)) {\n    if (found.closest('[data-key]')?.getAttribute('data-key') === key) return found;\n  }\n  return null;\n}`,
    );
  }
  return blocks.join('\n\n');
}

function declarationsBlock(name, contract, includeRender) {
  const camel = lowerFirst(name);
  const lines = [];
  if (includeRender) {
    const inputsDefault = Object.values(contract.inputs).every(
      (input) => input.optional,
    )
      ? '?'
      : '';
    const slotsDefault = Object.keys(contract.slots).length === 0 ? '?' : '';
    lines.push(
      `export declare function render${name}(inputs${inputsDefault}: ${name}Inputs, slots${slotsDefault}: ${name}Slots): SafeHtml;`,
    );
  }
  lines.push(
    `export declare function wire${name}(root: HTMLElement, handlers: ${name}Handlers): () => void;`,
  );
  lines.push(
    `export declare function ${camel}Refs(root: ParentNode): ${name}Refs;`,
  );
  return lines.join('\n');
}

/**
 * Generates a view module. `options.source` names the document file in the
 * header; `options.resolveView(src)` loads composed documents (required when
 * the document has `#view` nodes); `options.target` is `ts` (default) or `js`;
 * `options.declarationsOnly` omits `render<Name>` for documents an app loads
 * at runtime through `interpretView`.
 *
 * Returns `{ code, declarations?, contract, digest }` — `declarations` is the
 * `.d.ts` for the `js` target. Throws on an invalid document.
 */
export function generateView(document, catalog, options = {}) {
  const contract = contractOf(document, catalog, {
    resolveView: options.resolveView,
  });
  const name = document.name;
  const camel = lowerFirst(name);
  const target = options.target === 'js' ? 'js' : 'ts';
  const imports = createImports();
  imports.type('kerfjs', 'SafeHtml');
  imports.value('kerfjs/actions', 'delegateActions');

  // Composed documents' names, so #view nodes import the right render function.
  const views = {};
  const collectViews = (node) => {
    if (!isObject(node)) return;
    if (node.type === '#view') views[node.src] = options.resolveView(node.src);
    for (const list of Object.values(isObject(node.zones) ? node.zones : {})) {
      for (const child of list) {
        if ('$each' in child) collectViews(child.template);
        else if ('$if' in child) {
          collectViews(child.then);
          collectViews(child.else);
        } else collectViews(child);
      }
    }
  };
  collectViews(document.root);

  let rootExpr;
  if (!options.declarationsOnly) {
    rootExpr = printDoc(
      createEmitter(
        { ...document, views },
        catalog,
        imports,
        options.importFrom,
      ).root(document.root),
      2,
    );
  }
  const digest = contractDigest(contract);
  const sourceDigest = viewDigest(canonicalJson(document));
  const sourceName = options.source ?? `${camel}.kui.json`;
  const types = typesBlock(name, contract);
  const contractLine = `export const ${camel}Contract = ${literal(digest)};`;

  const assemble = (body) =>
    `${header(sourceName, contract, sourceDigest, body)}\n${body}`;
  if (target === 'ts') {
    const body = [
      imports.render(true),
      types,
      contractLine,
      functionsBlock(name, contract, rootExpr, true),
    ].join('\n\n');
    return { code: assemble(`${body}\n`), contract, digest };
  }
  const code = [
    imports.render(false),
    contractLine,
    functionsBlock(name, contract, rootExpr, false),
  ].join('\n\n');
  const dts = [
    `import type { SafeHtml } from 'kerfjs';`,
    types,
    `export declare const ${camel}Contract: ${literal(digest)};`,
    declarationsBlock(name, contract, rootExpr !== undefined),
  ].join('\n\n');
  return {
    code: assemble(`${code}\n`),
    declarations: assemble(`${dts}\n`),
    contract,
    digest,
  };
}
