#!/usr/bin/env node

import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { projectConsumerCatalog } from './catalog-projection.mjs';

const usage =
  'Usage: kerf-catalog-demo --extension <catalog.json> --out <catalog.generated.ts> --repo-base <blob-url> [--kerf-catalog <catalog.json>] [--category <name>] [--source-template <path>] [--demo-template <path>] [--documentation-template <path>] [--design-template <path>] (--write|--check)';

function parseArgs(argv) {
  const options = {};
  const values = new Map([
    ['--extension', 'extension'],
    ['--out', 'out'],
    ['--repo-base', 'repoBase'],
    ['--kerf-catalog', 'kerfCatalog'],
    ['--category', 'category'],
    ['--source-template', 'sourceTemplate'],
    ['--demo-template', 'demoTemplate'],
    ['--documentation-template', 'documentationTemplate'],
    ['--design-template', 'designTemplate'],
  ]);
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === '--check' || arg === '--write') {
      if (options.mode)
        throw new Error('Choose exactly one of --write or --check');
      options.mode = arg;
    } else if (values.has(arg)) {
      const value = argv[++index];
      if (!value || value.startsWith('--'))
        throw new Error(`${arg} needs a value`);
      options[values.get(arg)] = value;
    } else {
      throw new Error(`Unknown option ${arg}`);
    }
  }
  if (!options.mode || !options.extension || !options.out || !options.repoBase)
    throw new Error(usage);
  if (!/^https?:\/\//.test(options.repoBase))
    throw new Error('--repo-base must be an HTTP(S) URL');
  return options;
}

export function renderConsumerCatalog(rows, repoBase) {
  const base = repoBase.endsWith('/') ? repoBase : `${repoBase}/`;
  return (
    '// Generated by kerf-catalog-demo. Do not edit.\n' +
    `export const catalogRepositoryBlobUrl = ${JSON.stringify(base)} as const;\n` +
    `export const generatedConsumerCatalog = ${JSON.stringify(rows, null, 2)} as const;\n`
  );
}

export async function runCatalogProjection(argv) {
  const options = parseArgs(argv);
  const extension = JSON.parse(
    await readFile(resolve(options.extension), 'utf8'),
  );
  const kerfCatalog = JSON.parse(
    await readFile(
      options.kerfCatalog
        ? resolve(options.kerfCatalog)
        : new URL('./ai/component-catalog.json', import.meta.url),
      'utf8',
    ),
  );
  const rows = projectConsumerCatalog(extension, kerfCatalog, options);
  const output = renderConsumerCatalog(rows, options.repoBase);
  const outputPath = resolve(options.out);
  if (options.mode === '--write') {
    await writeFile(outputPath, output);
    process.stdout.write(`Wrote ${outputPath}\n`);
  } else {
    let current;
    try {
      current = await readFile(outputPath, 'utf8');
    } catch {
      // A missing generated file is the same drift as stale content.
    }
    if (current !== output)
      throw new Error(`${outputPath} is stale; run kerf-catalog-demo --write`);
    process.stdout.write(`${outputPath} is in sync.\n`);
  }
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  runCatalogProjection(process.argv.slice(2)).catch((error) => {
    process.stderr.write(`kerf-catalog-demo: ${error.message}\n`);
    process.exitCode = 1;
  });
}
