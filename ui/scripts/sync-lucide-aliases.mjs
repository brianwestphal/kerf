// Writes the editor icon picker's Lucide name table (KF-NTK7YW: one tile per
// icon, under Lucide's own name) from the installed lucide's
// `iconsAndAliases.mjs`, where each line exports an icon's canonical name
// and its aliases from `./icons/<canonical-name>.mjs`. `--check` fails when
// the committed table is stale.
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';

const root = fileURLToPath(new URL('..', import.meta.url));
const target = resolve(root, 'src/editor/model/lucide-aliases.generated.ts');
const check = process.argv.includes('--check');

const require = createRequire(import.meta.url);
const lucideRoot = dirname(require.resolve('lucide/package.json'));
const { version } = JSON.parse(
  await readFile(resolve(lucideRoot, 'package.json'), 'utf8'),
);
const source = await readFile(
  resolve(lucideRoot, 'dist/esm/iconsAndAliases.mjs'),
  'utf8',
);

/** `arrow-down-a-z` → `ArrowDownAZ`, as Lucide names its exports. */
const exportOf = (file) =>
  file
    .split('-')
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join('');
/** A split at every case and digit boundary (`ArrowDownAZ` → `arrow-down-a-z`). */
const split = (name) =>
  name
    .replace(/([a-z0-9])(?=[A-Z])|([A-Za-z])(?=[0-9])|([A-Z])(?=[A-Z])/g, '$&-')
    .replace(/([0-9])(?=[0-9])/g, '$1-')
    .toLowerCase();

const aliases = [];
const names = {};
for (const [, list, file] of source.matchAll(
  /export \{ (.+?) \} from '\.\/icons\/([\w-]+)\.mjs'/g,
)) {
  const canonical = exportOf(file);
  for (const [, name] of list.matchAll(/default as (\w+)/g))
    if (name !== canonical) aliases.push(name);
  if (split(canonical) !== file) names[canonical] = file;
}
aliases.sort();

const raw = `// Generated by scripts/sync-lucide-aliases.mjs from lucide ${version}; do not edit.

/**
 * Lucide exports that alias another icon (KF-NTK7YW): the icon picker shows
 * each icon once, under its canonical name.
 */
export const LUCIDE_ALIASES: ReadonlySet<string> = new Set(${JSON.stringify(aliases, null, 2)});

/** Canonical names a case and digit split of the export does not give. */
export const LUCIDE_NAMES: Readonly<Record<string, string>> = ${JSON.stringify(names, null, 2)};
`;
const content = await format(raw, {
  ...(await resolveConfig(target)),
  filepath: target,
});

const current = await readFile(target, 'utf8').catch(() => '');
if (check) {
  if (current !== content) {
    console.error(
      `${target} is stale. Run \`npm run lucide-aliases:sync\` and commit the result.`,
    );
    process.exit(1);
  }
  console.log('[sync-lucide-aliases] OK');
} else if (current !== content) {
  await writeFile(target, content);
  console.log(
    `[sync-lucide-aliases] wrote ${aliases.length} aliases and ${Object.keys(names).length} names`,
  );
}
