// Measures the @kerfjs/ui/view runtime entries for scripts/check-view-bundle.mjs
// (KF-CTCNWJ: view bundle budget).
import { fileURLToPath } from 'node:url';
import { gzipSync } from 'node:zlib';

import { build } from 'esbuild';

const root = fileURLToPath(new URL('../..', import.meta.url));

/** A string only generate.mjs contains; a runtime bundle must not. */
export const GENERATOR_MARKER = 'GENERATED by kerf-ui-view';

export const ENTRIES = {
  interpretView: "export { interpretView } from './view/interpret.mjs';",
  validateView:
    "export { createViewCatalog, validateView } from './view/validate.mjs';",
};

/** Minified, gzipped size of one entry, plus its minified text. */
export async function measureEntry(source) {
  const result = await build({
    stdin: { contents: source, resolveDir: root, loader: 'js' },
    bundle: true,
    minify: true,
    format: 'esm',
    platform: 'browser',
    external: ['kerfjs', 'kerfjs/*'],
    write: false,
    logLevel: 'silent',
  });
  const text = result.outputFiles[0].text;
  return { gzip: gzipSync(text, { level: 9 }).length, text };
}
