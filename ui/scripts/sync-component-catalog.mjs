import { readFile, writeFile } from 'node:fs/promises';

import { projectCatalogEntries } from '../catalog-projection.mjs';
import { COMPONENTS } from './build-design-templates.mjs';

const check = process.argv.includes('--check');
const catalogUrl = new URL('../ai/component-catalog.json', import.meta.url);
const generatedUrl = new URL(
  '../ux-demo/catalog.generated.ts',
  import.meta.url,
);
const catalog = JSON.parse(await readFile(catalogUrl, 'utf8'));
const implementationSources = new Map();
for (const entry of catalog.entries) {
  if (entry.source !== 'kerf' || entry.kind !== 'component') continue;
  const module = (
    entry.delivery.browserImport ?? entry.delivery.moduleImport
  ).slice('@kerfjs/ui/'.length);
  const facade = await readFile(
    new URL(`../src/${module}.tsx`, import.meta.url),
    'utf8',
  );
  const target = /from '[.]\/([^']+)[.]js';/.exec(facade)?.[1] ?? module;
  implementationSources.set(module, `ui/src/${target}.tsx`);
}

// A component with a committed SVG design template (docs/design/templates/<id>.svg,
// keyed by the same slug as the catalog entry id). Kept in sync with the design
// template manifest so the demo footer links only where a template exists.
const templateSlugs = new Set(Object.keys(COMPONENTS));
const designTemplate = (entry) =>
  entry.source === 'kerf' &&
  entry.kind === 'component' &&
  templateSlugs.has(entry.id)
    ? `ui/docs/design/templates/${entry.id}.svg`
    : undefined;

const demoSource = (entry) => {
  if (entry.kind === 'recipe')
    return `ui/ux-demo/recipes/${entry.id.slice('recipe-'.length)}.tsx`;
  if (entry.source === 'webawesome') return 'ui/ux-demo/webawesome-demos.tsx';
  return `ui/ux-demo/demos/${entry.id}.tsx`;
};

const componentSource = (entry) => {
  if (entry.source !== 'kerf' || entry.kind !== 'component') return undefined;
  const module = (
    entry.delivery.browserImport ?? entry.delivery.moduleImport
  ).slice('@kerfjs/ui/'.length);
  return implementationSources.get(module);
};

const projection = {
  demoSource,
  componentSource,
  designTemplate,
  documentation: (entry) => `ui/${entry.links.documentation}`,
};
const kerf = projectCatalogEntries(
  catalog.entries.filter((entry) => entry.source === 'kerf'),
  projection,
);
const webAwesome = projectCatalogEntries(
  catalog.entries.filter((entry) => entry.source === 'webawesome'),
  projection,
);
const generated =
  `// Generated by scripts/sync-component-catalog.mjs from ai/component-catalog.json. Do not edit.\n` +
  `export const generatedKerfCatalog = ${JSON.stringify(kerf, null, 2)} as const;\n\n` +
  `export const generatedWebAwesomeCatalog = ${JSON.stringify(webAwesome, null, 2)} as const;\n`;

if (check) {
  let current = '';
  try {
    current = await readFile(generatedUrl, 'utf8');
  } catch {
    // The actionable failure below also covers a missing generated file.
  }
  if (current !== generated) {
    console.error(
      '[sync-component-catalog] ux-demo/catalog.generated.ts is stale; run npm run catalog:sync.',
    );
    process.exitCode = 1;
  } else {
    console.log(
      '[sync-component-catalog] component catalog projection is in sync.',
    );
  }
} else {
  await writeFile(generatedUrl, generated);
  console.log('[sync-component-catalog] wrote ux-demo/catalog.generated.ts.');
}
