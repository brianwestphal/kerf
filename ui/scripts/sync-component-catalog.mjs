import { readFile, writeFile } from 'node:fs/promises';

const check = process.argv.includes('--check');
const catalogUrl = new URL('../ai/component-catalog.json', import.meta.url);
const generatedUrl = new URL('../ux-demo/catalog.generated.ts', import.meta.url);
const catalog = JSON.parse(await readFile(catalogUrl, 'utf8'));

const project = (entry) => ({
  id: entry.id,
  name: entry.name,
  category: entry.category,
  kind: entry.kind,
  source: entry.source,
  description: entry.purpose,
  uses: entry.uses ?? [],
});
const kerf = catalog.entries.filter((entry) => entry.source === 'kerf').map(project);
const webAwesome = catalog.entries.filter((entry) => entry.source === 'webawesome').map(project);
const generated = `// Generated by scripts/sync-component-catalog.mjs from ai/component-catalog.json. Do not edit.\n`
  + `export const generatedKerfCatalog = ${JSON.stringify(kerf, null, 2)} as const;\n\n`
  + `export const generatedWebAwesomeCatalog = ${JSON.stringify(webAwesome, null, 2)} as const;\n`;

if (check) {
  let current = '';
  try {
    current = await readFile(generatedUrl, 'utf8');
  } catch {
    // The actionable failure below also covers a missing generated file.
  }
  if (current !== generated) {
    console.error('[sync-component-catalog] ux-demo/catalog.generated.ts is stale; run npm run catalog:sync.');
    process.exitCode = 1;
  } else {
    console.log('[sync-component-catalog] component catalog projection is in sync.');
  }
} else {
  await writeFile(generatedUrl, generated);
  console.log('[sync-component-catalog] wrote ux-demo/catalog.generated.ts.');
}
