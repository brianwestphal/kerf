import { raw } from 'kerfjs';
import { afterEach, describe, expect, it, vi } from 'vitest';

import { Pane } from '../../src/components/layout/pane/pane.js';
import { SunkenPanel } from '../../src/components/surfaces/sunken-panel/sunken-panel.js';
import {
  ensureSunkenTexture,
  SUNKEN_TEXTURE_PROPERTY,
  sunkenTextureDataUrl,
  sunkenTexturePixels,
} from '../../src/shared/styles/sunken-texture.js';

const root = () => document.documentElement;

afterEach(() => {
  root().style.removeProperty(SUNKEN_TEXTURE_PROPERTY);
  vi.restoreAllMocks();
});

/** A minimal 2D canvas whose PNG encodes the pixels it was given. */
function stubCanvas() {
  let drawn: Uint8ClampedArray | undefined;
  const toDataURL = vi.fn(
    () => `data:image/png;base64,${String(drawn?.length ?? 0)}`,
  );
  const context = {
    createImageData: (width: number, height: number) => ({
      data: new Uint8ClampedArray(width * height * 4),
    }),
    putImageData: (image: { data: Uint8ClampedArray }) => {
      drawn = image.data;
    },
  };
  const create = document.createElement.bind(document);
  vi.spyOn(document, 'createElement').mockImplementation(
    (tag: string, options?: ElementCreationOptions) => {
      if (tag !== 'canvas') return create(tag, options);
      return {
        width: 0,
        height: 0,
        getContext: () => context,
        toDataURL,
      } as unknown as HTMLCanvasElement;
    },
  );
  return { toDataURL, drawn: () => drawn };
}

describe('sunken texture', () => {
  it('draws the same monochrome Gaussian tile every time, within 4% opacity', () => {
    const pixels = sunkenTexturePixels();
    expect(pixels).toHaveLength(100 * 100 * 4);
    expect(sunkenTexturePixels()).toEqual(pixels);
    let dark = 0;
    let light = 0;
    let maxAlpha = 0;
    for (let offset = 0; offset < pixels.length; offset += 4) {
      const [r, g, b, a] = pixels.slice(offset, offset + 4);
      expect(r).toBe(g);
      expect(g).toBe(b);
      expect([0, 255]).toContain(r);
      maxAlpha = Math.max(maxAlpha, a!);
      if (a! > 0) {
        if (r === 0) dark += 1;
        else light += 1;
      }
    }
    // Clipped at 2.5σ, the strongest grains reach exactly 4% (alpha 10).
    expect(maxAlpha).toBe(Math.round(0.04 * 255));
    // Grains lighten and darken in roughly equal measure.
    expect(Math.abs(dark - light) / (dark + light)).toBeLessThan(0.1);
  });

  it('installs the tile once per document as a private custom property', () => {
    const canvas = stubCanvas();
    ensureSunkenTexture();
    const value = root().style.getPropertyValue(SUNKEN_TEXTURE_PROPERTY);
    expect(value).toBe('url("data:image/png;base64,40000")');
    expect(canvas.drawn()).toEqual(sunkenTexturePixels());
    ensureSunkenTexture();
    ensureSunkenTexture(document);
    expect(canvas.toDataURL).toHaveBeenCalledTimes(1);
  });

  it('leaves the flat surface without a document or a 2D canvas', () => {
    expect(() => ensureSunkenTexture(undefined)).not.toThrow();
    const create = document.createElement.bind(document);
    vi.spyOn(document, 'createElement').mockImplementation(
      (tag: string, options?: ElementCreationOptions) =>
        tag === 'canvas'
          ? ({ getContext: () => null } as unknown as HTMLCanvasElement)
          : create(tag, options),
    );
    expect(sunkenTextureDataUrl()).toBeUndefined();
    ensureSunkenTexture();
    expect(root().style.getPropertyValue(SUNKEN_TEXTURE_PROPERTY)).toBe('');
  });

  it('is generated by the sunken surfaces that render, not by other surfaces', () => {
    const canvas = stubCanvas();
    String(Pane({ children: raw('Plain') }));
    expect(canvas.toDataURL).not.toHaveBeenCalled();
    String(Pane({ appearance: 'sunken', children: raw('Lowered') }));
    expect(canvas.toDataURL).toHaveBeenCalledTimes(1);
    root().style.removeProperty(SUNKEN_TEXTURE_PROPERTY);
    String(SunkenPanel({ children: raw('Group') }));
    expect(canvas.toDataURL).toHaveBeenCalledTimes(2);
  });
});
